const QUEST_THAI_LEVEL_TOPIC_INDEXES: Record<number, number[]> = {
  1: [0, 1],
  2: [2, 3],
  3: [4, 5],
  4: [6, 7],
  5: [8],
};

const createQuestion = (level: number, topicIndex: number, item: RawQuestQuestion, questionIndex: number): Question => ({
  id: 69000 + level * 1000 + (topicIndex + 1) * 100 + questionIndex + 1,
  subject: item.subject,
  question: item.question,
  options: [item.answer, ...item.distractors],
  correctAnswer: 0,
  explanation: item.explanation,
});

const createLevelBank = (level: number): Question[] => {
  const topicIndexes = QUEST_THAI_LEVEL_TOPIC_INDEXES[level] || [];
  return topicIndexes.flatMap(topicIndex =>
    THAI_TOPIC_BANKS[topicIndex].questions.map((item, questionIndex) =>
      createQuestion(level, topicIndex, item, questionIndex),
    ),
  );
};

export const QUEST_THAI_LEVEL_DURATION_SECONDS = 3600;

export const QUEST_THAI_LEVEL_QUESTION_BANK: Record<number, Question[]> = {
  1: createLevelBank(1),
  2: createLevelBank(2),
  3: createLevelBank(3),
  4: createLevelBank(4),
  5: createLevelBank(5),
};

const shuffleArray = <T,>(items: T[]): T[] => {
  const next = [...items];
  for (let index = next.length - 1; index > 0; index -= 1) {
    const targetIndex = Math.floor(Math.random() * (index + 1));
    [next[index], next[targetIndex]] = [next[targetIndex], next[index]];
  }
  return next;
};

const shuffleQuestionOptions = (question: Question): Question => {
  const shuffledOptions = shuffleArray(
    question.options.map((option, index) => ({ option, originalIndex: index })),
  );

  return {
    ...question,
    options: shuffledOptions.map(item => item.option),
    correctAnswer: shuffledOptions.findIndex(item => item.originalIndex === question.correctAnswer),
  };
};

const getBalancedLevelQuestions = (level: number, count: number): Question[] => {
  const topicIndexes = QUEST_THAI_LEVEL_TOPIC_INDEXES[level] || [];
  if (topicIndexes.length <= 1) {
    return shuffleArray(QUEST_THAI_LEVEL_QUESTION_BANK[level] || []).slice(0, count);
  }

  const baseCount = Math.floor(count / topicIndexes.length);
  const remainder = count % topicIndexes.length;
  return topicIndexes.flatMap((topicIndex, index) => {
    const topicQuestions = THAI_TOPIC_BANKS[topicIndex].questions.map((item, questionIndex) =>
      createQuestion(level, topicIndex, item, questionIndex),
    );
    return shuffleArray(topicQuestions).slice(0, baseCount + (index < remainder ? 1 : 0));
  });
};

export const hasQuestThaiLevelExam = (level: number) => Object.prototype.hasOwnProperty.call(QUEST_THAI_LEVEL_TOPIC_INDEXES, level);

export const getQuestThaiLevelQuestions = (level: number, count = 30): Question[] =>
  shuffleArray(getBalancedLevelQuestions(level, count)).map(shuffleQuestionOptions);
