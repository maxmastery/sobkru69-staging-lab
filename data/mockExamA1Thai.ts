const ROTATION_STORAGE_KEY = 'sobkru:a1-thai-exam-used-question-ids:v1';

const shuffleQuestions = <T,>(items: T[]): T[] => {
  const shuffled = [...items];

  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled;
};

const readUsedQuestionIds = (): number[] => {
  if (typeof window === 'undefined') return [];

  try {
    const raw = window.localStorage.getItem(ROTATION_STORAGE_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.filter((id): id is number => typeof id === 'number') : [];
  } catch {
    return [];
  }
};

const writeUsedQuestionIds = (ids: number[]) => {
  if (typeof window === 'undefined') return;

  try {
    window.localStorage.setItem(ROTATION_STORAGE_KEY, JSON.stringify(ids));
  } catch {
    // If storage is unavailable, the exam still works with in-memory randomization for this attempt.
  }
};

export const getPartA1ThaiExamQuestions = (
  count = PART_A1_THAI_EXAM_META.currentQuestionCount,
): Question[] => {
  const safeCount = Math.min(count, PART_A1_THAI_QUESTIONS.length);
  const questionIds = new Set(PART_A1_THAI_QUESTIONS.map((question) => question.id));
  const usedIds = new Set(readUsedQuestionIds().filter((id) => questionIds.has(id)));
  let nextUsedIds = new Set(usedIds);
  let availableQuestions = PART_A1_THAI_QUESTIONS.filter((question) => !usedIds.has(question.id));

  if (availableQuestions.length < safeCount) {
    availableQuestions = PART_A1_THAI_QUESTIONS;
    nextUsedIds = new Set();
  }

  const selectedQuestions = shuffleQuestions(availableQuestions).slice(0, safeCount);

  selectedQuestions.forEach((question) => {
    nextUsedIds.add(question.id);
  });

  if (nextUsedIds.size >= PART_A1_THAI_QUESTIONS.length) {
    writeUsedQuestionIds(selectedQuestions.map((question) => question.id));
  } else {
    writeUsedQuestionIds([...nextUsedIds]);
  }

  return selectedQuestions;
};
