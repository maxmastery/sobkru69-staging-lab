const MATH_ROTATION_STORAGE_KEY = 'sobkru:a1-math-exam-used-question-ids:v1';
const VERY_HARD_MATH_QUESTION_IDS = new Set([100, 110, 120, 130, 140, 150, 160, 170, 180, 190, 200, 210, 220, 230, 240]);

const shuffleQuestions = <T,>(items: T[]): T[] => {
  const shuffled = [...items];

  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled;
};

const readUsedQuestionIds = (key: string): number[] => {
  if (typeof window === 'undefined') return [];

  try {
    const raw = window.localStorage.getItem(key);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed.filter((id): id is number => typeof id === 'number') : [];
  } catch {
    return [];
  }
};

const writeUsedQuestionIds = (key: string, ids: number[]) => {
  if (typeof window === 'undefined') return;

  try {
    window.localStorage.setItem(key, JSON.stringify(ids));
  } catch {
    // If storage is unavailable, this exam still randomizes inside the current attempt.
  }
};

const pickRotatingQuestions = (pool: Question[], count: number, key: string): Question[] => {
  const poolIds = new Set(pool.map((question) => question.id));
  const usedIds = new Set(readUsedQuestionIds(key).filter((id) => poolIds.has(id)));
  let availableQuestions = pool.filter((question) => !usedIds.has(question.id));
  let nextUsedIds = new Set(usedIds);

  if (availableQuestions.length < count) {
    availableQuestions = pool;
    nextUsedIds = new Set();
  }

  const selectedQuestions = shuffleQuestions(availableQuestions).slice(0, count);
  selectedQuestions.forEach((question) => nextUsedIds.add(question.id));

  if (nextUsedIds.size >= pool.length) {
    writeUsedQuestionIds(key, selectedQuestions.map((question) => question.id));
  } else {
    writeUsedQuestionIds(key, [...nextUsedIds]);
  }

  return selectedQuestions;
};

export const getPartA1MathExamQuestions = (
  count = PART_A1_MATH_EXAM_META.questionCount,
): Question[] => {
  const safeCount = Math.min(count, PART_A1_MATH_QUESTIONS.length);
  const blockCount = Math.ceil(safeCount / 10);
  const hardCount = Math.min(blockCount, VERY_HARD_MATH_QUESTION_IDS.size);
  const regularCount = safeCount - hardCount;
  const veryHardPool = PART_A1_MATH_QUESTIONS.filter((question) => VERY_HARD_MATH_QUESTION_IDS.has(question.id));
  const regularPool = PART_A1_MATH_QUESTIONS.filter((question) => !VERY_HARD_MATH_QUESTION_IDS.has(question.id));
  const selectedHardQuestions = pickRotatingQuestions(
    veryHardPool,
    hardCount,
    `${MATH_ROTATION_STORAGE_KEY}:very-hard`,
  );
  const selectedRegularQuestions = pickRotatingQuestions(
    regularPool,
    regularCount,
    `${MATH_ROTATION_STORAGE_KEY}:regular`,
  );
  const questions: Question[] = [];

  for (let blockIndex = 0; blockIndex < blockCount; blockIndex += 1) {
    const blockRegularQuestions = selectedRegularQuestions.slice(blockIndex * 9, blockIndex * 9 + 9);
    const hardQuestion = selectedHardQuestions[blockIndex];
    const blockQuestions = [...blockRegularQuestions];

    if (hardQuestion) {
      const insertAt = Math.floor(Math.random() * (blockQuestions.length + 1));
      blockQuestions.splice(insertAt, 0, hardQuestion);
    }

    questions.push(...blockQuestions);
  }

  return questions.slice(0, safeCount);
};
